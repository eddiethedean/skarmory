use std::collections::BTreeSet;
use std::fs;
use std::path::Path;
use std::process::Command;

use serde_json::Value;

fn put(root: &Path, name: &str, text: &str) {
    let file = root.join(name);
    fs::create_dir_all(file.parent().unwrap()).unwrap();
    fs::write(file, text).unwrap();
}

fn project(root: &Path) {
    put(root, "go.mod", "module example.org/reach\n\ngo 1.22\n");
}

fn scan(root: &Path, args: &[&str], exit_code: i32) -> Value {
    let output = Command::new(env!("CARGO_BIN_EXE_skarmory"))
        .current_dir(root)
        .env_remove("SKYLOS_CONFIG_FILE")
        .env_remove("DJANGO_SETTINGS_MODULE")
        .args(["--profile", "skylos-0.3", "--no-grep-verify", "."])
        .args(args)
        .output()
        .unwrap();
    assert_eq!(
        output.status.code(),
        Some(exit_code),
        "{}\n{}",
        String::from_utf8_lossy(&output.stderr),
        String::from_utf8_lossy(&output.stdout)
    );
    serde_json::from_slice(&output.stdout).unwrap()
}

fn unreachable(report: &Value) -> BTreeSet<&str> {
    report["unused_functions"]
        .as_array()
        .unwrap()
        .iter()
        .map(|finding| {
            assert_eq!(finding["rule_id"], "SKY-U001");
            finding["full_name"].as_str().unwrap()
        })
        .collect()
}

fn reachable(report: &Value) -> BTreeSet<&str> {
    report["dead_code_evidence"]["symbols"]
        .as_array()
        .unwrap()
        .iter()
        .map(|row| row["qualified_name"].as_str().unwrap())
        .collect()
}

#[test]
fn go_pinned_unrooted_recursion_and_mutual_calls() {
    let tree = tempfile::tempdir().unwrap();
    let root = tree.path();
    // Exact generated input from Skylos 5.7.0 (Apache-2.0), pinned at 87978e69.
    // skylos/engines/go/internal/symbols/reachability_test.go:13-20,189.
    put(root, "go.mod", "module example.com/demo\n\ngo 1.22\n");
    put(
        root,
        "main.go",
        "package main\nfunc main() { keep() }\nfunc keep() {}\nfunc staleA() { staleB() }\nfunc staleB() { staleA() }\nfunc self() { self() }\n",
    );
    let report = scan(root, &[], 0);
    assert_eq!(report["analysis_summary"]["languages"]["Go"], 1);
    assert_eq!(report["coverage"]["extracted_files"], 1);
    assert_eq!(report["coverage"]["status"], "complete");
    assert_eq!(
        unreachable(&report),
        BTreeSet::from(["self", "staleA", "staleB"])
    );
    assert_eq!(reachable(&report), BTreeSet::from(["keep", "main"]));
}

#[test]
fn go_same_module_imports_and_typed_receivers_preserve_identity() {
    let tree = tempfile::tempdir().unwrap();
    let root = tree.path();
    project(root);
    put(
        root,
        "main.go",
        r#"package main
import p "example.org/reach/provider"
type Local[T any] struct{}
type Other struct{}
func (*Local[T]) run() { live() }
func (Other) run() {}
func dead() {}
func live() {}
func main() {
    var local Local[int]
    callback := local.run
    p.Invoke(callback)
    dead := func() {}
    dead()
}
"#,
    );
    put(
        root,
        "provider/runner.go",
        "package runner\nfunc Invoke(callback func()) { callback() }\nfunc unused() {}\n",
    );
    let report = scan(root, &[], 0);
    assert_eq!(report["coverage"]["status"], "complete");
    assert_eq!(
        unreachable(&report),
        BTreeSet::from(["Other.run", "dead", "provider.unused"])
    );
    assert_eq!(
        reachable(&report),
        BTreeSet::from(["Local.run", "live", "main", "provider.Invoke"])
    );

    put(root, "go.mod", "module moved.example/reach\n\ngo 1.22\n");
    let report = scan(root, &[], 2);
    assert_eq!(
        report["coverage"]["issues"][0]["kind"],
        "unresolved_go_import"
    );
    assert!(unreachable(&report).is_empty());
}

#[test]
fn go_test_and_generated_entrypoints_keep_only_reached_helpers() {
    let tree = tempfile::tempdir().unwrap();
    let root = tree.path();
    project(root);
    put(
        root,
        "handlers.go",
        "package handlers\nfunc testHandler() {}\nfunc generatedHandler() {}\nfunc obsolete() {}\n",
    );
    put(
        root,
        "handlers_test.go",
        "package handlers\nimport \"testing\"\nfunc TestPresent(t *testing.T) { testHandler() }\nfunc unusedHelper() {}\n",
    );
    put(
        root,
        "startup.pb.go",
        "// Code generated by a tool. DO NOT EDIT.\npackage handlers\nfunc startup() { generatedHandler() }\n",
    );

    let report = scan(root, &[], 0);
    assert_eq!(report["coverage"]["status"], "complete");
    assert_eq!(
        unreachable(&report),
        BTreeSet::from(["obsolete", "unusedHelper"])
    );
    assert_eq!(
        reachable(&report),
        BTreeSet::from(["TestPresent", "generatedHandler", "startup", "testHandler"])
    );

    put(
        root,
        "startup.s",
        "// An assembler may call a private helper.\n",
    );
    let report = scan(root, &[], 2);
    assert_eq!(
        report["coverage"]["issues"][0]["kind"],
        "unsupported_go_project_context"
    );
    assert!(unreachable(&report).is_empty());
}

#[test]
fn go_cached_parallel_scan_rebuilds_edges_after_an_edit() {
    let tree = tempfile::tempdir().unwrap();
    let root = tree.path().join("project");
    let cache = tree.path().join("cache");
    project(&root);
    put(&root, "main.go", "package main\nfunc main() { first() }\n");
    put(
        &root,
        "functions.go",
        "package main\nfunc first() {}\nfunc second() {}\n",
    );
    let cache_flags = ["--workers", "4", "--cache-dir", cache.to_str().unwrap()];
    let _ = scan(&root, &cache_flags, 0);
    put(&root, "main.go", "package main\nfunc main() { second() }\n");
    let mut warm = scan(&root, &cache_flags, 0);
    warm.as_object_mut().unwrap().remove("cache");
    let clean = scan(&root, &[], 0);
    assert_eq!(clean, warm);
    assert_eq!(unreachable(&warm), BTreeSet::from(["first"]));
}

#[test]
fn unused_go_package_variable_preserves_initializer_side_effects() {
    let tree = tempfile::tempdir().unwrap();
    let root = tree.path();
    project(root);
    put(
        root,
        "main.go",
        concat!(
            "package main\n",
            "var (\n",
            "    startup = initialize()\n",
            "    configured = 1\n",
            "    runtimeValue = configured\n",
            ")\n",
            "func initialize() int { return 2 }\n",
            "func main() { println(runtimeValue) }\n",
        ),
    );

    let report = scan(root, &[], 0);
    assert_eq!(report["coverage"]["status"], "complete");
    assert!(unreachable(&report).is_empty());
    assert_eq!(
        reachable(&report),
        BTreeSet::from(["configured", "initialize", "main", "runtimeValue"]),
    );
    let variables = report["unused_variables"].as_array().unwrap();
    assert_eq!(variables.len(), 1);
    assert_eq!(variables[0]["rule_id"], "SKY-U003");
    assert_eq!(variables[0]["full_name"], "startup");
}
